const fs = require("fs");
const path = require("path");

const input = process.argv[2];
if (!input) {
  console.error("Usage: node tools/build-jmdict.js <jmdict-eng-common.json>");
  process.exit(1);
}
const src = JSON.parse(fs.readFileSync(input, "utf8"));

// ---- kana → romaji (Hepburn, website ke baaki data jaisa: "ou", "ii", "kk") ----
const R2K = {
  a:"あ",i:"い",u:"う",e:"え",o:"お", ka:"か",ki:"き",ku:"く",ke:"け",ko:"こ", ga:"が",gi:"ぎ",gu:"ぐ",ge:"げ",go:"ご",
  sa:"さ",shi:"し",su:"す",se:"せ",so:"そ", za:"ざ",ji:"じ",zu:"ず",ze:"ぜ",zo:"ぞ",
  ta:"た",chi:"ち",tsu:"つ",te:"て",to:"と", da:"だ",de:"で",do:"ど", na:"な",ni:"に",nu:"ぬ",ne:"ね",no:"の",
  ha:"は",hi:"ひ",fu:"ふ",he:"へ",ho:"ほ", ba:"ば",bi:"び",bu:"ぶ",be:"べ",bo:"ぼ", pa:"ぱ",pi:"ぴ",pu:"ぷ",pe:"ぺ",po:"ぽ",
  ma:"ま",mi:"み",mu:"む",me:"め",mo:"も", ya:"や",yu:"ゆ",yo:"よ", ra:"ら",ri:"り",ru:"る",re:"れ",ro:"ろ", wa:"わ",o_:"を",
  kya:"きゃ",kyu:"きゅ",kyo:"きょ", gya:"ぎゃ",gyu:"ぎゅ",gyo:"ぎょ", sha:"しゃ",shu:"しゅ",sho:"しょ", ja:"じゃ",ju:"じゅ",jo:"じょ",
  cha:"ちゃ",chu:"ちゅ",cho:"ちょ", nya:"にゃ",nyu:"にゅ",nyo:"にょ", hya:"ひゃ",hyu:"ひゅ",hyo:"ひょ", bya:"びゃ",byu:"びゅ",byo:"びょ",
  pya:"ぴゃ",pyu:"ぴゅ",pyo:"ぴょ", mya:"みゃ",myu:"みゅ",myo:"みょ", rya:"りゃ",ryu:"りゅ",ryo:"りょ",
  fa:"ふぁ",fi:"ふぃ",fe:"ふぇ",fo:"ふぉ", ti:"てぃ",di:"でぃ",she:"しぇ",che:"ちぇ",je:"じぇ",wi:"うぃ",we:"うぇ",
  va:"ゔぁ",vi:"ゔぃ",vu:"ゔ",ve:"ゔぇ",vo:"ゔぉ", tu:"とぅ", du:"どぅ"
};
const K2R = {};
for (const [r, k] of Object.entries(R2K)) if (!K2R[k]) K2R[k] = r.replace("_", "");
Object.assign(K2R, { "ぢ": "ji", "づ": "zu", "ゐ": "i", "ゑ": "e",
  "うぉ": "wo", "うぁ": "wa", "つぁ": "tsa", "つぃ": "tsi", "つぇ": "tse", "つぉ": "tso",
  "でゅ": "dyu", "てゅ": "tyu", "ふゅ": "fyu", "くぁ": "kwa", "ぐぁ": "gwa", "いぇ": "ye" });
// Greetings mein は ko "wa" padhte hain
const SPECIAL_ROMAJI = { "こんにちは": "konnichiwa", "こんばんは": "konbanwa" };

const kataToHira = s => s.replace(/[\u30a1-\u30f6]/g, c => String.fromCharCode(c.charCodeAt(0) - 0x60));

function toRomaji(kana) {
  const s = kataToHira(kana);
  let out = "", dbl = false;
  for (let i = 0; i < s.length;) {
    const two = s.substr(i, 2), one = s[i];
    let r;
    if (two.length === 2 && K2R[two]) { r = K2R[two]; i += 2; }
    else if (one === "っ") { dbl = true; i++; continue; }
    else if (one === "ん") { r = /^[aiueoy]/.test(romajiAhead(s, i + 1)) ? "n'" : "n"; i++; }
    else if (one === "ー") { r = (out.match(/[aiueo]$/) || [""])[0]; i++; }
    else if (K2R[one]) { r = K2R[one]; i++; }
    else if (/[・＝\s]/.test(one)) { r = " "; i++; }
    else return ""; // ajeeb character: romaji chhod do
    if (dbl) { r = (r[0] === "c" ? "t" : r[0]) + r; dbl = false; }
    out += r;
  }
  return out.replace(/\s+/g, " ").trim();
}
function romajiAhead(s, i) {
  const two = s.substr(i, 2), one = s[i];
  return K2R[two] || K2R[one] || "";
}

// ---- Har entry ko [jp, kana, romaji, english] mein badlo ----
const out = [];
for (const w of src.words) {
  const kana = (w.kana.find(k => k.common) || w.kana[0]);
  if (!kana) continue;
  const kanjiList = w.kanji.filter(k => k.common);
  const kanji = kanjiList[0] || w.kanji[0];
  // "usually written in kana" wale words kana mein hi dikhao
  const kanaOnly = w.sense.every(s => s.misc.includes("uk"));
  const jp = kanji && !kanaOnly ? kanji.text : kana.text;
  // Pehle 3 meanings, har ek mein max 3 English words
  const senses = w.sense.slice(0, 3).map(s => s.gloss.filter(g => g.lang === "eng").slice(0, 3).map(g => g.text).join(", ")).filter(Boolean);
  if (!senses.length) continue;
  const en = senses.join("; ");
  out.push([jp, kana.text, SPECIAL_ROMAJI[kana.text] || toRomaji(kana.text), en.length > 160 ? en.slice(0, 157) + "..." : en]);
}

const header = `// AUTO-GENERATED by tools/build-jmdict.js. Haath se edit mat karo.
// Source: JMdict (common entries) via jmdict-simplified ${src.version}, dict date ${src.dictDate}
// JMdict © Electronic Dictionary Research and Development Group (EDRDG), https://www.edrdg.org/
// License: Creative Commons Attribution-ShareAlike 4.0 (CC BY-SA 4.0), https://creativecommons.org/licenses/by-sa/4.0/
// Modified: sirf pehli kana/kanji, pehle 3 meanings, aur romaji joda gaya.
// Format: [Japanese, kana, romaji, English meanings]
`;
const body = `window.JMDICT_INFO = ${JSON.stringify({ version: src.version, date: src.dictDate, count: out.length })};\n` +
  `window.JMDICT = ${JSON.stringify(out)};\n`;
const target = path.join(__dirname, "..", "js", "data", "jmdict", "jmdict-common.js");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, header + body);
console.log(`Wrote ${out.length} entries, ${(fs.statSync(target).size / 1024 / 1024).toFixed(2)} MB → ${target}`);
console.log("No-romaji entries:", out.filter(e => !e[2]).length);
