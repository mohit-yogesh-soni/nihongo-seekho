// JMdict (jmdict-simplified "eng-common" JSON) ko website ke liye chhoti file mein badalta hai.
//
// Kaise chalayein (jab naya JMdict version lena ho):
//   1. https://github.com/scriptin/jmdict-simplified/releases se "jmdict-eng-common-*.json.zip" download karke unzip karo
//   2. node tools/build-jmdict.js path/to/jmdict-eng-common-X.json
//   Output: js/data/jmdict/jmdict-common.js
